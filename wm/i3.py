GENERATED_HEADER = [
    "# CAUTION: This file has been auto-generated by Zenith Shell.",
    "# Any manual changes WILL BE OVERWRITTEN on the next startup.",
]


# temporary workaround until my rounded-corners i3 patch is ready and picom shadows work as expected.
def ensure_vibrancy(hex_color: str, min_brightness=0.8, min_saturation=0.5) -> str:
    hex_color = hex_color.lstrip("#")

    r, g, b = hex_to_rgb01(hex_color=hex_color)
    h, s, v = colorsys.rgb_to_hsv(r, g, b)

    new_v = max(v, min_brightness)
    new_s = max(s, min_saturation)

    r, g, b = colorsys.hsv_to_rgb(h, new_s, new_v)
    return f"#{int(r * 255):02x}{int(g * 255):02x}{int(b * 255):02x}"


def _write_atomic(path: Path, text: str):
    temp_path = path.with_suffix(".tmp")
    with open(temp_path, "w") as f:
        f.write(text)
    os.replace(temp_path, path)


def _configured_keybindings() -> list[KeyBinding]:
    try:
        i3_config_node: ConfigNode = config.get_node("bindings.i3")
        overrides = i3_config_node.get_all()
    except AttributeError:
        logger.error("Failed to load wm keybind overrides")
        overrides = {}
    return apply_keybinding_overrides(I3_KEYBINDINGS, overrides)


def _adapt_system_config(text: str, our_keys: set[str]) -> str:
    """Drop what would fight the shell: the default bar, and bindings we also define."""
    lines = []
    bar_depth = 0
    for line in text.splitlines():
        stripped = line.strip()
        if bar_depth or re.match(r"bar\s*\{", stripped):
            bar_depth += stripped.count("{") - stripped.count("}")
            continue
        binding = re.match(r"bindsym\s+(?:--\S+\s+)*(\S+)", stripped)
        if binding and binding.group(1) in our_keys:
            line = f"# replaced by {SHELL_NAME}: {line}"
        lines.append(line)
    return "\n".join(lines) + "\n"


class I3WM(WindowManager):
    name = "i3"
    label = "i3"
    exec_flags = "--no-startup-id"

    def __init__(self):
        self.config_dir = Path.home() / f".config/{self.name}"
        self.config_path = self.config_dir / "config"
        self.glob_dir = self.config_dir / "conf.d"
        self.borders_conf = self.glob_dir / "borders.conf"
        self.keybinds_conf = self.glob_dir / "keybinds.conf"
        self.general_conf = self.glob_dir / "general.conf"

    # live changes, i3 picks everything up on reload instead
    def _live(self, command: str):
        pass

    def _ensure_paths(self):
        self.config_dir.mkdir(parents=True, exist_ok=True)
        self.glob_dir.mkdir(parents=True, exist_ok=True)

    def _seed_main_config(self):
        """A user config replaces the system one entirely, so start from the system defaults.
        Otherwise adding our lines would leave the WM without its basic keybindings.
        An existing config is the user's and is never rewritten."""
        if self.config_path.exists():
            return
        logger.warning(
            "{} config not found at {}. Creating new one.", self.name, self.config_path
        )
        system_config = Path(f"/etc/{self.name}/config")
        if system_config.is_file():
            our_keys = {b.key for b in _configured_keybindings()}
            self.config_path.write_text(
                _adapt_system_config(system_config.read_text(), our_keys)
            )
        else:
            self.config_path.touch()

    def _ensure_glob_include(self):
        include_line = f"include {self.glob_dir}/*.conf"

        self._seed_main_config()

        content = self.config_path.read_text()

        if include_line not in content:
            logger.info("Adding include line to {} config", self.name)
            suffix = "\n" if content and not content.endswith("\n") else ""
            with open(self.config_path, "a") as f:
                f.write(f"{suffix}# globbing all .conf in /conf.d\n{include_line}\n")
        else:
            logger.debug("{} config already contains include line", self.name)

    def _main_config_defines_mod(self) -> bool:
        return (
            re.search(r"^\s*set\s+\$mod\s", self.config_path.read_text(), re.MULTILINE)
            is not None
        )

    def reload(self):
        try:
            i3_resp = get_i3_connection().send_command("reload")
            success = all(
                r.get("success", False) for r in i3_resp.reply if isinstance(r, dict)
            )
            if not success:
                logger.error("{} config failed to reload: {}", self.name, i3_resp.reply)
            else:
                logger.info("Reloaded the {} config", self.name)
        except Exception as e:
            logger.error("Error reloading {} config: {}", self.name, e)

    def add_autostart(self):
        self._ensure_paths()
        include_line = (
            f"# {SHELL_NAME} startup\nexec {self.exec_flags} {SHELL_NAME + '-shell'}"
        )

        self._seed_main_config()

        content = self.config_path.read_text()

        if include_line not in content:
            logger.info("Adding {} startup to {} config", SHELL_NAME, self.name)
            prefix = "\n" if content and not content.endswith("\n") else ""

            with open(self.config_path, "a") as f:
                f.write(f"\n{prefix}{include_line}\n")
        else:
            logger.debug("{} config already contains {} startup", self.name, SHELL_NAME)

    def write_theme(self, color: str | None = None, reload: bool = False):
        self._ensure_paths()
        colors_css = ROOT_DIR / "styles" / "colors.css"

        theme_available = True

        if color is None:
            if colors_css.exists():
                color = get_css_variable(str(colors_css), "--primary")
            else:
                color = "#5e81ac"
                theme_available = False

        logger.debug("Setting {} focused border color to {}", self.name, color)

        enabled = theme_available and config.get("i3.borders.matugen")
        border_conf = [
            *GENERATED_HEADER,
            "# To change these bindings, use Settings or edit:",
            f"#   {CONFIG_FILE}  OR",
            f"#   {ROOT_DIR}/wm/i3.py  OR",
            "",
            f"{'' if enabled else '# '}client.focused          {color} {color} {color} {color}",
            "# client.focused_inactive #ff0000 #ff0000 #ff0000 #ff0000",
            "# client.unfocused        #ff0000 #ff0000 #ff0000 #ff0000",
            "# client.urgent           #ff0000 #ff0000 #ff0000 #ff0000",
        ]
        _write_atomic(self.borders_conf, "\n".join(border_conf))

        if reload:
            self.reload()

    def build_keybinds_text(
        self, bindings: list[KeyBinding], define_mod: bool = False
    ) -> str:
        lines = [
            *GENERATED_HEADER,
            "# To change these bindings, edit I3_KEYBINDINGS in:",
            f"#   {ROOT_DIR}/config/bindings.py",
            "",
        ]

        if define_mod:
            # i3 ignores a modifier it doesn't know, so `$mod+d` would bind the plain d key
            lines += ["# your config does not set $mod", "set $mod Mod4", ""]

        for b in bindings:
            lines.append(f"bindsym {b.key} exec {self.exec_flags} {b.command}")

        return "\n".join(lines)

    def write_keybinds(self, reload: bool = False):
        logger.debug("Setting {} keybinds", self.name)
        self._ensure_paths()

        try:
            self._ensure_glob_include()
            text = self.build_keybinds_text(
                _configured_keybindings(),
                define_mod=not self._main_config_defines_mod(),
            )
            _write_atomic(self.keybinds_conf, text)
            logger.info("Wrote {} keybindings to {}", self.name, self.keybinds_conf)

            if reload:
                self.reload()

        except Exception as e:
            logger.error("Failed to apply keybindings: {}", e)

    def _dock_lines(self, gaps_config: ConfigNode) -> list[str]:
        # sway reserves room through the dock's exclusive zone, i3 only does that
        # for docks at the top or bottom
        bar_position = config.get("bar.POSITION")
        if bar_position not in ("left", "right"):
            return []
        outer = gaps_config.get("props.outer") if gaps_config.get("enabled") else 0
        return [
            "# side dock",
            f"gaps {bar_position} {DOCK_THICKNESS + (outer or 0)}px",
            (
                f'for_window [window_role="{namespaces.DOCK}"] '
                "floating enable, sticky enable, border none"
            ),
            "",
        ]

    def _border_lines(self, border_config: ConfigNode) -> list[str]:
        return []

    def _rule_lines(self) -> list[str]:
        return []

    def build_general_text(self) -> str:
        lines = []

        gaps_config: ConfigNode = config.get_node("i3.gaps")
        if gaps_config.get("enabled"):
            lines.append("# gaps")
            for prop, val in gaps_config.get_node("props").get_all().items():
                lines.append(f"gaps {prop} {val}px")
                self._live(f"gaps {prop} all set {val}")
            lines.append("")

        lines.extend(self._dock_lines(gaps_config))

        border_config = config.get_node("i3.borders")
        if border_config.get("enabled"):
            lines.append("# borders")
            lines.append(
                f"default_border pixel {border_config.get('props.border_width')}"
            )
            lines.append("default_floating_border none")
            lines.append("")

            lines.extend(self._border_lines(border_config))

            if border_config.get("props.smart_borders"):
                lines.append("smart_borders on")
                lines.append("")

        lines.extend(self._rule_lines())

        return "\n".join(lines)

    def write_general(self, reload: bool = False):
        self._ensure_paths()

        lines = [
            *GENERATED_HEADER,
            "# To change these bindings, edit:",
            f"#   {CONFIG_FILE}",
            "",
        ]

        try:
            self._ensure_glob_include()

            logger.debug("Setting {} borders and gaps", self.name)
            lines.append(self.build_general_text())

            _write_atomic(self.general_conf, "\n".join(lines) + "\n")
            logger.info("Wrote {} gaps and borders to {}", self.name, self.general_conf)

            if reload:
                self.reload()

        except Exception as e:
            logger.error("Failed to generate {} general config: {}", self.name, e)

    def exit_session(self):
        I3.send_command("exit")

    def focus_shell_window(self, role: str):
        I3.send_command(f'[window_role="^{role}$"] focus')

    def unfocus_shell_window(self):
        I3.send_command("focus mode_toggle")

    def get_screen_size(self) -> tuple[int, int]:
        from fabric.i3.service import I3MessageType

        reply = get_i3_connection().send_command("", I3MessageType.GET_OUTPUTS).reply
        active = [
            o for o in reply if o.get("active") and not o["name"].startswith("xroot")
        ]

        if not active:
            raise RuntimeError(f"No active {self.name} outputs")

        max_x = max(o["rect"]["x"] + o["rect"]["width"] for o in active)
        max_y = max(o["rect"]["y"] + o["rect"]["height"] for o in active)

        return max_x, max_y

    def find_conflicts(self, config_path=None) -> list:
        return find_wm_conflicts(self.name, config_path)

    def get_corner_radius(self) -> int | None:
        # what every window gets rounded to, None when we don't set it
        borders = config.get_node("i3.borders")
        if not self.can_round_corners or not borders.get("enabled"):
            return None
        return borders.get("props.corner_radius")

    def build_workspaces(self, vertical: bool = False):
        from modules.workspaces.workspaces import Workspaces

        return Workspaces(vertical=vertical)

    def build_active_window(self):
        from modules.workspaces.workspaces import ActiveWindow

        return ActiveWindow()
