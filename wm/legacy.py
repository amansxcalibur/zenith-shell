import re
from pathlib import Path

# what pre zenith.d installs left in i3/sway configs, delete this file once nobody has them
HEADER = "# CAUTION: This file has been auto-generated by Zenith Shell."
CONF_FILES = ("keybinds.conf", "general.conf", "borders.conf")
EXEC = r"^# zenith startup\nexec\b.*\bzenith-shell$"
WMS = ("i3", "sway")


def _is_ours(path: Path) -> bool:
    try:
        return path.read_text(errors="ignore").startswith(HEADER)
    except OSError:
        return False


def has_legacy_config(wm: str) -> bool:
    if wm not in WMS:
        return False
    config_dir = Path.home() / ".config" / wm
    if any(_is_ours(config_dir / "conf.d" / name) for name in CONF_FILES):
        return True
    try:
        text = (config_dir / "config").read_text(errors="ignore")
    except OSError:
        return False
    return re.search(EXEC, text, re.MULTILINE) is not None


def migrate_conf_d(config_path: Path, exec_flags: str) -> bool:
    old_dir = config_path.parent / "conf.d"
    for name in CONF_FILES:
        if _is_ours(old_dir / name):
            (old_dir / name).unlink()

    content = config_path.read_text()
    old_exec = f"# zenith startup\nexec {exec_flags} zenith-shell\n"
    # we wrote it with a blank line in front, take that too
    old_exec = f"\n{old_exec}" if f"\n{old_exec}" in content else old_exec
    migrated = content.replace(old_exec, "")
    old_include = f"# globbing all .conf in /conf.d\ninclude {old_dir}/*.conf\n"
    # drop the dir only with its include, so nothing points at a missing dir
    if old_include in migrated and old_dir.is_dir() and not any(old_dir.iterdir()):
        old_dir.rmdir()
        migrated = migrated.replace(old_include, "")
    if migrated == content:
        return False
    # write in place, the config may be a dotfiles symlink
    config_path.write_text(migrated)
    return True
