def _reload_i3():
    try:
        i3_resp = get_i3_connection().send_command("reload")
        success = all(
            r.get("success", False) for r in i3_resp.reply if isinstance(r, dict)
        )
        if not success:
            logger.error("{} config failed to reload: {}", WM, i3_resp.reply)
        else:
            logger.info("Reloaded the {} config", WM)
    except Exception as e:
        logger.error("Error reloading {} config: {}", WM, e)


# temporary workaround until my rounded-corners i3 patch is ready and picom shadows work as expected.
def ensure_vibrancy(hex_color: str, min_brightness=0.8, min_saturation=0.5) -> str:
    hex_color = hex_color.lstrip("#")

    r, g, b = hex_to_rgb01(hex_color=hex_color)
    h, s, v = colorsys.rgb_to_hsv(r, g, b)

    new_v = max(v, min_brightness)
    new_s = max(s, min_saturation)

    r, g, b = colorsys.hsv_to_rgb(h, new_s, new_v)
    return f"#{int(r * 255):02x}{int(g * 255):02x}{int(b * 255):02x}"


def generate_i3_border_theme_config(hex_color: str | None = None, reload: bool = False):
    ensure_i3_paths()
    STYLES_DIR = ROOT_DIR / "styles"
    COLORS_CSS_PATH = STYLES_DIR / "colors.css"

    theme_available = True

    if hex_color is None:
        if COLORS_CSS_PATH.exists():
            raw_color = get_css_variable(str(COLORS_CSS_PATH), "--primary")
            hex_color = raw_color
        else:
            hex_color = "#5e81ac"
            theme_available = False

    logger.debug("Setting {} focused border color to {}", WM, hex_color)

    border_conf = [
        "# CAUTION: This file has been auto-generated by Zenith Shell.",
        "# Any manual changes WILL BE OVERWRITTEN on the next startup.",
        "# To change these bindings, use Settings or edit:",
        f"#   {CONFIG_FILE}  OR",
        f"#   {ROOT_DIR}/config/i3/utils.py  OR",
        "",
        f"{'' if (theme_available and config.get('i3.borders.matugen')) else '# '}client.focused          {hex_color} {hex_color} {hex_color} {hex_color}",
        "# client.focused_inactive #ff0000 #ff0000 #ff0000 #ff0000",
        "# client.unfocused        #ff0000 #ff0000 #ff0000 #ff0000",
        "# client.urgent           #ff0000 #ff0000 #ff0000 #ff0000",
    ]

    temp_path = BORDERS_CONF_PATH.with_suffix(".tmp")
    with open(temp_path, "w") as f:
        f.write("\n".join(border_conf))
    os.replace(temp_path, BORDERS_CONF_PATH)

    if reload:
        _reload_i3()


def generate_i3_keybinds(bindings: list[KeyBinding], define_mod: bool = False) -> str:
    lines = [
        "# CAUTION: This file has been auto-generated by Zenith Shell.",
        "# Any manual changes WILL BE OVERWRITTEN on the next startup.",
        "# To change these bindings, edit I3_KEYBINDINGS in:",
        f"#   {ROOT_DIR}/config/bindings.py",
        "",
    ]

    if define_mod:
        # i3 ignores a modifier it doesn't know, so `$mod+d` would bind the plain d key
        lines += ["# your config does not set $mod", "set $mod Mod4", ""]

    for b in bindings:
        lines.append(
            f"bindsym {b.key} exec {'' if IS_WAYLAND else '--no-startup-id'} {b.command}"
        )

    return "\n".join(lines)


def _adapt_system_config(text: str, our_keys: set[str]) -> str:
    """Drop what would fight the shell: the default bar, and bindings we also define."""
    lines = []
    bar_depth = 0
    for line in text.splitlines():
        stripped = line.strip()
        if bar_depth or re.match(r"bar\s*\{", stripped):
            bar_depth += stripped.count("{") - stripped.count("}")
            continue
        binding = re.match(r"bindsym\s+(?:--\S+\s+)*(\S+)", stripped)
        if binding and binding.group(1) in our_keys:
            line = f"# replaced by {SHELL_NAME}: {line}"
        lines.append(line)
    return "\n".join(lines) + "\n"


def _seed_main_config(config_path: Path):
    """A user config replaces the system one entirely, so start from the system defaults.
    Otherwise adding our lines would leave the WM without its basic keybindings.
    An existing config is the user's and is never rewritten."""
    if config_path.exists():
        return
    logger.warning("{} config not found at {}. Creating new one.", WM, config_path)
    system_config = Path(f"/etc/{WM}/config")
    if system_config.is_file():
        our_keys = {b.key for b in _configured_keybindings()}
        config_path.write_text(
            _adapt_system_config(system_config.read_text(), our_keys)
        )
    else:
        config_path.touch()


def _configured_keybindings() -> list[KeyBinding]:
    try:
        i3_config_node: ConfigNode = config.get_node("bindings.i3")
        overrides = i3_config_node.get_all()
    except AttributeError:
        logger.error("Failed to load {}wm keybind overrides", WM)
        overrides = {}
    return apply_keybinding_overrides(I3_KEYBINDINGS, overrides)


def _main_config_defines_mod(config_path: Path) -> bool:
    return (
        re.search(r"^\s*set\s+\$mod\s", config_path.read_text(), re.MULTILINE)
        is not None
    )


def ensure_i3_config_includes_glob_dir(config_path: Path, include_dir: Path):
    include_line = f"include {include_dir}/*.conf"

    _seed_main_config(config_path)

    content = config_path.read_text()

    if include_line not in content:
        logger.info("Adding include line to {} config", WM)
        suffix = "\n" if content and not content.endswith("\n") else ""
        with open(config_path, "a") as f:
            f.write(f"{suffix}# globbing all .conf in /conf.d\n{include_line}\n")
    else:
        logger.debug("{} config already contains include line", WM)


def get_i3_config_path() -> Path:
    return CONFIG_PATH


def ensure_i3_paths():
    CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    CONFIG_GLOB_PATH.mkdir(parents=True, exist_ok=True)


def generate_i3_keybinds_config(reload: bool = False):
    logger.debug("Setting {} keybinds", WM)

    ensure_i3_paths()
    main_config_path = get_i3_config_path()

    try:
        ensure_i3_config_includes_glob_dir(main_config_path, CONFIG_GLOB_PATH)

        bindings = _configured_keybindings()

        # TODO
        # validate_keybindings(bindings)
        config_str = generate_i3_keybinds(
            bindings, define_mod=not _main_config_defines_mod(main_config_path)
        )

        temp_path = KEYBINDS_CONF_PATH.with_suffix(".tmp")
        with open(temp_path, "w") as f:
            f.write(config_str)
        os.replace(temp_path, KEYBINDS_CONF_PATH)
        logger.info("Wrote {} keybindings to {}", WM, KEYBINDS_CONF_PATH)

        if reload:
            _reload_i3()

    except Exception as e:
        logger.error("Failed to apply keybindings: {}", e)


def generate_i3_gaps_and_borders_config():
    lines = []

    gaps_config: ConfigNode = config.get_node("i3.gaps")
    if gaps_config.get("enabled"):
        lines.append("# gaps")
        for prop, val in gaps_config.get_node("props").get_all().items():
            lines.append(f"gaps {prop} {val}px")
            if IS_WAYLAND and os.environ.get("SWAYSOCK"):
                exec_shell_command_async(f"swaymsg gaps {prop} all set {val}")
        lines.append("")

    # sway reserves room through the dock's exclusive zone, i3 only does that
    # for docks at the top or bottom
    bar_position = config.get("bar.POSITION")
    if not IS_WAYLAND and bar_position in ("left", "right"):
        outer = gaps_config.get("props.outer") if gaps_config.get("enabled") else 0
        lines.extend(
            [
                "# side dock",
                f"gaps {bar_position} {DOCK_THICKNESS + (outer or 0)}px",
                (
                    'for_window [window_role="zenith-dock"] '
                    "floating enable, sticky enable, border none"
                ),
                "",
            ]
        )

    border_config = config.get_node("i3.borders")
    if border_config.get("enabled"):
        lines.append("# borders")
        lines.append(f"default_border pixel {border_config.get('props.border_width')}")
        lines.append("default_floating_border none")
        lines.append("")

        if border_config.get("props.smart_borders"):
            lines.append("smart_borders on")
            lines.append("")

    if IS_WAYLAND:
        config_block = [
            "# floating settings win",
            f'for_window [app_id="{SHELL_NAME}-settings"] {{',
            "    floating enable",
            "    border none",
        ]
        if is_swayfx():
            config_block.extend(
                [
                    "    shadows disable",
                    "    blur disable",
                ]
            )
        config_block.append("}")
        lines.append("\n".join(config_block))

    return "\n".join(lines)


def generate_i3_general_config(reload: bool = False):
    ensure_i3_paths()
    main_config_path = get_i3_config_path()

    lines = [
        "# CAUTION: This file has been auto-generated by Zenith Shell.",
        "# Any manual changes WILL BE OVERWRITTEN on the next startup.",
        "# To change these bindings, edit:",
        f"#   {CONFIG_FILE}",
        "",
    ]

    try:
        ensure_i3_config_includes_glob_dir(main_config_path, CONFIG_GLOB_PATH)

        logger.debug("Setting i3 borders and gaps")
        lines.append(generate_i3_gaps_and_borders_config())

        temp_path = GENERAL_CONF_PATH.with_suffix(".tmp")
        with open(temp_path, "w") as f:
            f.write("\n".join(lines) + "\n")
        os.replace(temp_path, GENERAL_CONF_PATH)
        logger.info("Wrote {} gaps and borders to {}", WM, GENERAL_CONF_PATH)

        if reload:
            _reload_i3()

    except Exception as e:
        logger.error("Failed to generate {} general config: {}", WM, e)


def add_shell_startup_to_i3_config():
    ensure_i3_paths()
    include_line = f"# {SHELL_NAME} startup\nexec {'' if IS_WAYLAND else '--no-startup-id'} {SHELL_NAME + '-shell'}"
    config_path = get_i3_config_path()

    _seed_main_config(config_path)

    content = config_path.read_text()

    if include_line not in content:
        logger.info("Adding {} startup to {} config", SHELL_NAME, WM)
        prefix = "\n" if content and not content.endswith("\n") else ""

        with open(config_path, "a") as f:
            f.write(f"\n{prefix}{include_line}\n")
    else:
        logger.debug("{} config already contains {} startup", WM, SHELL_NAME)


def is_swayfx() -> bool:
    from fabric.i3.service import I3MessageType

    try:
        reply = get_i3_connection().send_command("", I3MessageType.GET_VERSION)
    except Exception as e:  # no WM to ask, e.g. configuring sway from another session
        logger.debug("Could not query the window manager: {}", e)
        return False
    if reply.is_ok and isinstance(reply.reply, dict):
        return (
            "sway_original_version" in reply.reply
            and reply.reply.get("variant") == "sway"
        )
    return False
